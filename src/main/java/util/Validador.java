package util;

/**
 * Classe utilitária com validações básicas reutilizáveis em todo o sistema.
 *
 * Todos os métodos são estáticos ? não é necessário instanciar a classe.
 */
public class Validador {

    // Construtor privado: impede instanciação
    private Validador() {}

    // ???????????????????????????????????????????????????????????????
    // TEXTO
    // ???????????????????????????????????????????????????????????????

    /**
     * Verifica se uma String é nula ou vazia (incluindo apenas espaços).
     */
    public static boolean isVazio(String valor) {
        return valor == null || valor.trim().isEmpty();
    }

    /**
     * Verifica se uma String está preenchida.
     */
    public static boolean isPreenchido(String valor) {
        return !isVazio(valor);
    }

    /**
     * Verifica se uma String não ultrapassa o tamanho máximo permitido.
     *
     * @param valor  texto a verificar
     * @param max    tamanho máximo
     */
    public static boolean tamanhoValido(String valor, int max) {
        return valor != null && valor.trim().length() <= max;
    }

    // ???????????????????????????????????????????????????????????????
    // CNPJ
    // ???????????????????????????????????????????????????????????????

    /**
     * Valida um CNPJ verificando formato, sequências repetidas e dígitos verificadores.
     * Aceita CNPJ com ou sem máscara (ex: "12.345.678/0001-90" ou "12345678000190").
     *
     * @return true se o CNPJ for válido
     */
    public static boolean cnpjValido(String cnpj) {
        if (isVazio(cnpj)) return false;

        String c = cnpj.replaceAll("[^0-9]", "");

        if (c.length() != 14)          return false;
        if (c.matches("(\\d)\\1{13}")) return false; // ex: 00000000000000

        int[] p1 = {5, 4, 3, 2, 9, 8, 7, 6, 5, 4, 3, 2};
        int[] p2 = {6, 5, 4, 3, 2, 9, 8, 7, 6, 5, 4, 3, 2};

        int soma = 0;
        for (int i = 0; i < 12; i++) soma += Character.getNumericValue(c.charAt(i)) * p1[i];
        int d1 = soma % 11 < 2 ? 0 : 11 - (soma % 11);

        soma = 0;
        for (int i = 0; i < 13; i++) soma += Character.getNumericValue(c.charAt(i)) * p2[i];
        int d2 = soma % 11 < 2 ? 0 : 11 - (soma % 11);

        return d1 == Character.getNumericValue(c.charAt(12))
            && d2 == Character.getNumericValue(c.charAt(13));
    }

    // ???????????????????????????????????????????????????????????????
    // CPF
    // ???????????????????????????????????????????????????????????????

    /**
     * Valida um CPF verificando formato, sequências repetidas e dígitos verificadores.
     * Aceita CPF com ou sem máscara (ex: "123.456.789-09" ou "12345678909").
     *
     * @return true se o CPF for válido
     */
    public static boolean cpfValido(String cpf) {
        if (isVazio(cpf)) return false;

        String c = cpf.replaceAll("[^0-9]", "");

        if (c.length() != 11)         return false;
        if (c.matches("(\\d)\\1{10}")) return false; // ex: 11111111111

        int soma = 0;
        for (int i = 0; i < 9; i++) soma += Character.getNumericValue(c.charAt(i)) * (10 - i);
        int d1 = soma % 11 < 2 ? 0 : 11 - (soma % 11);

        soma = 0;
        for (int i = 0; i < 10; i++) soma += Character.getNumericValue(c.charAt(i)) * (11 - i);
        int d2 = soma % 11 < 2 ? 0 : 11 - (soma % 11);

        return d1 == Character.getNumericValue(c.charAt(9))
            && d2 == Character.getNumericValue(c.charAt(10));
    }

    // ???????????????????????????????????????????????????????????????
    // E-MAIL
    // ???????????????????????????????????????????????????????????????

    /**
     * Valida se o e-mail possui formato básico (contém @ e pelo menos um ponto após).
     *
     * @return true se o formato for válido
     */
    public static boolean emailValido(String email) {
        if (isVazio(email)) return false;
        return email.matches("^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$");
    }

    // ???????????????????????????????????????????????????????????????
    // NÚMEROS
    // ???????????????????????????????????????????????????????????????

    /**
     * Verifica se um número Double é positivo (maior que zero).
     */
    public static boolean isPositivo(Double valor) {
        return valor != null && valor > 0;
    }

    /**
     * Verifica se um número inteiro é positivo (maior que zero).
     */
    public static boolean isPositivo(Integer valor) {
        return valor != null && valor > 0;
    }

    // ???????????????????????????????????????????????????????????????
    // UF
    // ???????????????????????????????????????????????????????????????

    /**
     * Verifica se a UF informada é uma sigla de estado brasileiro válida.
     */
    public static boolean ufValida(String uf) {
        if (isVazio(uf)) return false;

        String[] ufs = {
            "AC","AL","AP","AM","BA","CE","DF","ES","GO",
            "MA","MT","MS","MG","PA","PB","PR","PE","PI",
            "RJ","RN","RS","RO","RR","SC","SP","SE","TO"
        };

        for (String s : ufs) {
            if (s.equalsIgnoreCase(uf.trim())) return true;
        }
        return false;
    }
}
